#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate ``src/tables.rs`` from the Python port (MBusinoLibPy).

Instead of re-typing the (large) lookup tables by hand, this script imports
the Python modules of the 1:1 port and emits Rust constants. The Python code
is itself a verified 1:1 port of the C++ original, so the generated tables
are the same data.

The entry counts are asserted against the Python side so a silent drift
(e.g. a table entry that gets dropped) fails loudly.

Run from the crate root::

    python3 tools/gen_tables.py

It writes ``src/tables.rs`` (do not edit that file by hand).
"""

from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CRATE = os.path.dirname(HERE)
WORKSPACE = os.path.dirname(CRATE)
PY_SRC = os.path.join(WORKSPACE, "MBusinoLibPy", "src")

sys.path.insert(0, PY_SRC)

from MBusinoLibPy.lookup_tables import (  # noqa: E402
    CODE_NAME,
    CODE_UNITS,
    DEVICE_CLASS,
    MEDIUM_NAMES,
    STATE_CLASS,
    _MEDIUM_TO_VOLUME_CLASS,
)
from MBusinoLibPy.vif_defs import VIF_DEFS, MBUS_VIF_DEF_NUM  # noqa: E402


def rust_str(value: str) -> str:
    """Rust string literal; keeps UTF-8 (m³, °C, ...) as-is."""
    out = ['"']
    for ch in value:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def gen_pairs(name: str, mapping) -> str:
    lines = [f"pub const {name}: &[(u32, &str)] = &["]
    for key, value in mapping.items():
        lines.append(f"    ({int(key)}u32, {rust_str(value)}),")
    lines.append("];")
    return "\n".join(lines)


def main() -> int:
    # --- safety nets: the generated data must match the Python source -------
    assert len(CODE_NAME) == 123, len(CODE_NAME)
    assert len(CODE_UNITS) == 79, len(CODE_UNITS)
    assert len(DEVICE_CLASS) == 120, len(DEVICE_CLASS)
    assert len(STATE_CLASS) == 122, len(STATE_CLASS)
    assert len(MEDIUM_NAMES) == 20, len(MEDIUM_NAMES)
    assert len(VIF_DEFS) == MBUS_VIF_DEF_NUM == 132, len(VIF_DEFS)

    parts = []
    parts.append("// @generated by tools/gen_tables.py - DO NOT EDIT BY HAND.")
    parts.append("//")
    parts.append("// Data source: the verified 1:1 Python port MBusinoLibPy")
    parts.append("// (lookup_tables.py / vif_defs.py), which in turn mirrors the C++")
    parts.append("// original MBusinoLib (GPL-3.0).")
    parts.append("")
    parts.append(
        "/// ``getCodeName()`` table: ``MBUS_CODE`` value -> record name.\n"
        "/// A missing key means the C++ ``default`` branch (empty string)."
    )
    parts.append(gen_pairs("CODE_NAME", CODE_NAME))
    parts.append("")
    parts.append(
        "/// ``getCodeUnits()`` table: ``MBUS_CODE`` value -> unit.\n"
        "/// A missing key means the C++ ``return 0`` (NULL) branch."
    )
    parts.append(gen_pairs("CODE_UNITS", CODE_UNITS))
    parts.append("")
    parts.append(
        "/// ``getDeviceClass()`` table: ``MBUS_CODE`` value -> Home Assistant\n"
        "/// ``device_class``. The three volume codes are handled separately."
    )
    parts.append(gen_pairs("DEVICE_CLASS", DEVICE_CLASS))
    parts.append("")
    parts.append(
        "/// ``getStateClass()`` table: ``MBUS_CODE`` value -> Home Assistant\n"
        "/// ``state_class``."
    )
    parts.append(gen_pairs("STATE_CLASS", STATE_CLASS))
    parts.append("")
    parts.append(
        "/// ``MEDIUM_NAMES``: M-Bus medium byte -> human readable name\n"
        "/// (``decodeHeader()``); missing keys -> ``\"Unknown\"``."
    )
    parts.append("pub const MEDIUM_NAMES: &[(u8, &str)] = &[")
    for key, value in MEDIUM_NAMES.items():
        parts.append(f"    ({int(key)}u8, {rust_str(value)}),")
    parts.append("];")
    parts.append("")
    parts.append(
        "/// ``_volumeClassFromMedium()`` table used for the volume codes."
    )
    parts.append("pub const MEDIUM_TO_VOLUME_CLASS: &[(u8, &str)] = &[")
    for key, value in _MEDIUM_TO_VOLUME_CLASS.items():
        parts.append(f"    ({int(key)}u8, {rust_str(value)}),")
    parts.append("];")
    parts.append("")
    parts.append(
        "/// Number of entries in ``VIF_DEFS`` (C++ ``MBUS_VIF_DEF_NUM``)."
    )
    parts.append(f"pub const MBUS_VIF_DEF_NUM: usize = {MBUS_VIF_DEF_NUM};")
    parts.append("")
    parts.append(
        "/// VIF definition table - order matters (``_findDefinition`` returns the\n"
        "/// FIRST match). Entry: ``(code, base, size, scalar)``."
    )
    parts.append("pub const VIF_DEFS: &[(u32, u32, u32, i8)] = &[")
    for code, base, size, scalar in VIF_DEFS:
        parts.append(
            f"    ({int(code)}u32, {int(base)}u32, {int(size)}u32, {int(scalar)}i8),"
        )
    parts.append("];")
    parts.append("")

    out_path = os.path.join(CRATE, "src", "tables.rs")
    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(parts))

    print("wrote", out_path)
    print("  CODE_NAME     ", len(CODE_NAME))
    print("  CODE_UNITS    ", len(CODE_UNITS))
    print("  DEVICE_CLASS  ", len(DEVICE_CLASS))
    print("  STATE_CLASS   ", len(STATE_CLASS))
    print("  MEDIUM_NAMES  ", len(MEDIUM_NAMES))
    print("  VIF_DEFS      ", len(VIF_DEFS))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
